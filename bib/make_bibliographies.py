#!/usr/bin/env python3
"""Build per-module and comprehensive bibliographies from bib/course.bib.

    python3 bib/make_bibliographies.py            # split + typeset everything
    python3 bib/make_bibliographies.py --check    # parse and compile only, no output kept

`course.bib` is the single source. Every entry carries a `keywords` field
(`d1`, `week01`, `unit1`, `session01`, ...); this splits the master file into
`bib/by-module/<keyword>.bib` and typesets one PDF per module plus one
comprehensive PDF covering everything.

Why bibtex and not biblatex: `biber` is not installed on the course machine,
and bibtex + the stock `plain` style needs no external .bst. That also means
titles must be brace-protected in course.bib, because `plain` lowercases
anything it is not told to leave alone.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

BIB_DIR = Path(__file__).resolve().parent
MASTER = BIB_DIR / "course.bib"
BY_MODULE = BIB_DIR / "by-module"
OUT = BIB_DIR / "build"

ENTRY_RE = re.compile(r"^@(\w+)\s*\{\s*([^,]+),", re.M)


def parse_entries(text: str) -> list[tuple[str, str, str]]:
    """Return [(key, entry_text, keywords)] by brace-matching each @entry."""
    out = []
    for m in ENTRY_RE.finditer(text):
        start = m.start()
        depth, i = 0, text.index("{", start)
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        entry = text[start:i + 1]
        kw = re.search(r"keywords\s*=\s*\{([^}]*)\}", entry)
        out.append((m.group(2).strip(), entry,
                    kw.group(1) if kw else ""))
    return out


def tex_for(title: str, bibname: str, subtitle: str) -> str:
    return rf"""\documentclass[11pt]{{article}}
\usepackage[T1]{{fontenc}}
\usepackage[utf8]{{inputenc}}
\usepackage[margin=1in]{{geometry}}
\usepackage{{url}}
\urlstyle{{same}}
\usepackage{{hyperref}}
\hypersetup{{colorlinks=true, urlcolor=blue, linkcolor=black}}
\begin{{document}}
\begin{{center}}
{{\Large\bfseries {title}}}\\[2pt]
{{\small CS 3892 / CS 5892 --- Formal Methods: Safe and Trustworthy AI, Fall 2026}}\\[2pt]
{{\small {subtitle}}}
\end{{center}}
\vspace{{1em}}
\nocite{{*}}
\bibliographystyle{{plain}}
\bibliography{{{bibname}}}
\end{{document}}
"""


def typeset(tex_path: Path, workdir: Path) -> tuple[bool, str]:
    stem = tex_path.stem
    for cmd in (["pdflatex", "-interaction=nonstopmode", stem],
                ["bibtex", stem],
                ["pdflatex", "-interaction=nonstopmode", stem],
                ["pdflatex", "-interaction=nonstopmode", stem]):
        r = subprocess.run(cmd, cwd=workdir, capture_output=True, text=True)
        if cmd[0] == "bibtex":
            bad = [l for l in r.stdout.splitlines()
                   if l.startswith(("Warning--", "I couldn't", "Repeated entry"))]
            if bad:
                return False, "; ".join(bad[:4])
    log = (workdir / f"{stem}.log").read_text(errors="replace")
    errs = [l for l in log.splitlines() if l.startswith("!")]
    if errs:
        return False, "; ".join(errs[:3])
    return (workdir / f"{stem}.pdf").exists(), ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify everything compiles, keep nothing")
    args = ap.parse_args()

    text = MASTER.read_text(encoding="utf-8")
    entries = parse_entries(text)
    print(f"parsed {len(entries)} entries from {MASTER.name}")

    untagged = [k for k, _, kw in entries if not kw.strip()]
    if untagged:
        print(f"  WARNING: no keywords on: {', '.join(untagged)}")

    groups: dict[str, list[str]] = {}
    for key, entry, kw in entries:
        for tag in (t.strip() for t in kw.split(",") if t.strip()):
            groups.setdefault(tag, []).append(entry)

    modules = sorted(t for t in groups if re.fullmatch(r"(d\d|week\d+|session\d+|unit\d+)", t))
    print(f"  module tags: {', '.join(modules)}")

    BY_MODULE.mkdir(exist_ok=True)
    OUT.mkdir(exist_ok=True)
    work = OUT / ".tex"
    work.mkdir(exist_ok=True)

    header = ("% GENERATED by bib/make_bibliographies.py from course.bib.\n"
              "% Do not edit: edit course.bib and regenerate.\n\n")
    jobs = [("course", "Comprehensive bibliography",
             f"All {len(entries)} verified references")]
    shutil.copy(MASTER, work / "course.bib")

    for tag in modules:
        name = f"{tag}"
        (BY_MODULE / f"{name}.bib").write_text(
            header + "\n\n".join(groups[tag]) + "\n", encoding="utf-8")
        shutil.copy(BY_MODULE / f"{name}.bib", work / f"{name}.bib")
        jobs.append((name, f"Bibliography --- {tag}",
                     f"{len(groups[tag])} reference(s)"))

    ok = True
    for bibname, title, subtitle in jobs:
        tex = work / f"{bibname}-bibliography.tex"
        tex.write_text(tex_for(title, bibname, subtitle), encoding="utf-8")
        good, err = typeset(tex, work)
        n = len(entries) if bibname == "course" else len(groups[bibname])
        print(f"  {'ok  ' if good else 'FAIL'} {bibname:12s} {n:2d} refs"
              f"{'' if good else '  -- ' + err}")
        ok &= good
        if good and not args.check:
            shutil.copy(work / f"{bibname}-bibliography.pdf",
                        OUT / f"{bibname}-bibliography.pdf")

    if args.check:
        shutil.rmtree(work, ignore_errors=True)
    else:
        print(f"\nPDFs in {OUT}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
